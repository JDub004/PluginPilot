// Renders docs/OPPORTUNITIES.md from src/discovery/opportunities.mjs.
import { writeFileSync } from 'node:fs';
import { ranked, WEIGHTS } from '../src/discovery/opportunities.mjs';

const rows = ranked();
const esc = (s) => String(s).replaceAll('|', '/');
const out = [];
out.push('# Opportunities (50, scored)', '');
out.push('Generated by `node scripts/render-opportunities.mjs` from `src/discovery/opportunities.mjs`. Do not edit by hand.', '');
out.push('## Scoring model', '');
out.push('Each factor is scored 1-5 and normalised; weights sum to 100:', '');
out.push('| Factor | Weight | Meaning |', '|---|---|---|');
const meaning = {
  pain: 'How much the problem hurts (money/time/risk)',
  freq: 'How often one user hits it',
  fit: 'Would a user naturally ask ChatGPT about this?',
  native: 'Native-substitution defence: 5 = plain ChatGPT clearly cannot do it',
  mcp: 'Can a small set of deterministic tools execute it?',
  wtp: 'Willingness to pay',
  comp: 'Competition (5 = little)',
  mvp: 'MVP simplicity (5 = 1-3 days)',
  ret: 'Retention / repeat use',
  dist: 'Distribution outside ChatGPT (SEO, social, communities)',
};
for (const [k, w] of Object.entries(WEIGHTS)) out.push(`| ${k} | ${w} | ${meaning[k]} |`);
out.push('', 'Changes vs. the brief: ChatGPT fit lowered 15→10 and a new **native** factor (13) added, because the official guidelines and the platform trend make "ChatGPT could do this alone" the single most common way a plugin dies. Frequency lowered 15→12 and MVP 10→7 to make room.', '');
out.push('**RISK_SCORE** (0-100) combines legal/regulatory, privacy, platform-absorption and data-access risk. **EXPECTED_VALUE = score × (1 − risk/200)**.', '');
out.push('All factor values are analyst judgements based on the evidence in MARKET_RESEARCH.md. They are hypotheses to be replaced with measured data.', '');
out.push('## Ranking', '');
out.push('| # | Opportunity | Score | Risk | EV | pain | freq | fit | native | mcp | wtp | comp | mvp | ret | dist | MVP days |');
out.push('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|');
rows.forEach((o, i) => {
  const s = o.scores;
  out.push(`| ${i + 1} | ${esc(o.name)} | ${o.score} | ${o.risk} | **${o.ev}** | ${s.pain} | ${s.freq} | ${s.fit} | ${s.native} | ${s.mcp} | ${s.wtp} | ${s.comp} | ${s.mvp} | ${s.ret} | ${s.dist} | ${o.mvpDays} |`);
});
out.push('', '## Detail', '');
rows.forEach((o, i) => {
  out.push(`### ${i + 1}. ${o.name} (\`${o.id}\`)`, '');
  out.push(`- **Target user:** ${o.targetUser}`);
  out.push(`- **Problem:** ${o.problem}`);
  out.push(`- **Current workaround:** ${o.workaround}`);
  out.push(`- **Example prompt:** "${o.examplePrompt}"`);
  out.push(`- **What the plugin adds beyond plain ChatGPT:** ${o.pluginEdge}`);
  out.push(`- **Existing alternatives:** ${o.alternatives}`);
  out.push(`- **Monetization:** ${o.monetization}`);
  out.push(`- **Score / Risk / EV:** ${o.score} / ${o.risk} / ${o.ev}`, '');
});
writeFileSync(new URL('../docs/OPPORTUNITIES.md', import.meta.url), out.join('\n'));
console.log(`wrote ${rows.length} opportunities`);
